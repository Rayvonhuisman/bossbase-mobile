// ---------------------------------------------------------------------------
// Hours
// ---------------------------------------------------------------------------
//
// The live database keeps two deliberately separate stores (migration
// 20260831140000_werkbon_uren):
//
//   werkbon_uren    — hours on a job: post-calculation, invoicing, the work
//                     order PDF. Write access follows the *job* (assignee,
//                     responsible, admin, planner).
//   urenregistratie — working-day hours: wages and leave. Write access follows
//                     the *person* (own rows, or admin/planner).
//
// Booking job hours into urenregistratie creates a second administration the
// dashboard's work order never reads, so hours on a werkbon go to werkbon_uren.

/** One row of `werkbon_uren` — hours booked on a work order. */
export type WerkbonUur = {
  id: string;
  company_id: string;
  werkbon_id: string;
  profile_id: string;
  datum: string; // YYYY-MM-DD
  start_tijd: string | null;
  eind_tijd: string | null;
  pauze_minuten: number;
  uren: number;
  reis_km: number | null;
  notitie: string | null;
  created_at: string;
  updated_at: string;
  medewerker?: ProfileSummary | null;
};

export type TimeEntryType = 'arbeid' | 'reistijd' | 'overhead' | 'overig';

/**
 * One row of `urenregistratie` — working-day hours (wages/leave).
 *
 * No work order, customer, deal or project: the dashboard dropped those
 * columns (migration 20260831140000). Job hours live in `werkbon_uren`.
 */
export type TimeEntry = {
  id: string;
  company_id: string;
  profile_id: string;
  datum: string; // YYYY-MM-DD
  start_tijd: string | null;
  eind_tijd: string | null;
  pauze_minuten: number | null;
  uren: number;
  type: TimeEntryType;
  notitie: string | null;
  created_at: string;
  updated_at: string;
};

/**
 * One line in the Uren tab. Both hour stores are shown together, so a total is
 * never silently short; `bron` says which table the row came from and
 * `werkbonLabel` names the job for a work-order hour.
 */
export type UrenRegel = TimeEntry & {
  bron: 'werkdag' | 'werkbon';
  /** De werkbon van een werkbonuur; altijd `null` bij een werkdaguur. */
  werkbon_id: string | null;
  werkbonLabel: string | null;
};
