/**
 * The status vocabulary of the live database, verified against
 * `public.werkbonnen` on project mawzqp… (2026-09-08):
 *
 *   gepland → in_uitvoering → afgerond
 *
 * These are the exact strings the dashboard writes and filters on, and the
 * value `afgerond` is what the DB trigger `sync_deal_stage_to_afgerond` keys
 * off. Writing English variants (`completed`, `in_progress`) produces rows the
 * dashboard renders as "Onbekend" and silently skips that trigger, so the app
 * must never invent its own spelling.
 */
export const WORK_ORDER_STATUSES = ['gepland', 'in_uitvoering', 'afgerond'] as const;
export type KnownWorkOrderStatus = (typeof WORK_ORDER_STATUSES)[number];
// `string & {}` keeps autocomplete for the known set but accepts any string,
// so a legacy or future value never crashes a screen.
export type WorkOrderStatus = KnownWorkOrderStatus | (string & {});

export type WorkOrder = {
  id: string;
  company_id: string;
  customer_id: string | null;
  deal_id: string | null;
  offerte_id: string | null;
  project_id: string | null;
  /** Voertuigen van de werkbon. uuid[] zonder FK sinds de dag-planning. */
  voertuig_ids: string[] | null;
  activity_id: string | null;
  /** Human-facing work-order number, e.g. "WB-005". Generated by a DB trigger. */
  nummer: string | null;
  /**
   * Legacy single-assignee column. The dashboard now assigns through
   * `assigned_to_ids`; a lot of live rows have `assigned_to` NULL while the
   * arrays are filled. Never filter on this column alone.
   */
  assigned_to: string | null;
  /** Everyone working on the job. RLS grants read access through this array. */
  assigned_to_ids: string[];
  /** Subset of `assigned_to_ids` that may also edit the job (RLS write gate). */
  verantwoordelijke_ids: string[];
  titel: string;
  omschrijving: string | null;
  status: WorkOrderStatus;
  gepland_op: string | null; // date (YYYY-MM-DD)
  starttijd: string | null; // HH:MM:SS
  eindtijd: string | null; // HH:MM:SS
  locatie: string | null;
  /** Planner remark on the job itself. The note *log* is `werkbon_notities`. */
  notes: string | null;
  /** Legacy free-text note column, superseded by the werkbon_notities table. */
  werkbon_notities: string | null;
  gestart_op: string | null; // timestamptz, set once on → in_uitvoering
  afgerond_op: string | null; // timestamptz, set on → afgerond
  /** Once set the job is signed off and DB triggers reject all child writes. */
  ondertekend_op: string | null;
  ondertekend_door_naam: string | null;
  created_at: string;
  updated_at: string;
};

